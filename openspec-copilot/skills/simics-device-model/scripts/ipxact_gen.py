"""
Simple IP-XACT to DML generator.

This script parses an IP-XACT component file (memoryMaps/registers) and
generates two basic DML output files: <device>.dml and <device>-registers.dml.

Usage: python3 ipxact_gen.py <ipxact-xml> -o <simics_device_path> -d <device_name>
"""
